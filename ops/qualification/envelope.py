"""Measure bounded qualification inputs; never opens an application database.

The source journal is read-only. Outputs, SQLite and I/O use a fresh TMPDIR
directory. Policy examples are contract models, not application acceptance.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import resource
import sqlite3
import tempfile
import time

import yaml


def main() -> None:
    root = Path(tempfile.mkdtemp(prefix='booksys-queue-envelope-'))
    source = Path('/data/booksys/state/state.yaml')
    raw = source.read_bytes()
    started = time.monotonic()
    parsed = yaml.safe_load(raw)
    parse_seconds = time.monotonic() - started
    assert isinstance(parsed, dict)
    # A representative larger journal with no private source content retained.
    larger = yaml.safe_dump({'entries': {str(i): {'url': f'https://invalid/{i}',
        'status': 'pending', 'first_eligible': '2026-11-09T00:00:00Z',
        'input_revision': 'a' * 64, 'method': 'v1'} for i in range(14000)}}).encode()
    assert len(larger) <= 4 * 1024 * 1024
    started = time.monotonic()
    assert isinstance(yaml.safe_load(larger), dict)
    larger_seconds = time.monotonic() - started
    (root / 'representative.yaml').write_bytes(larger)
    scans = []
    with sqlite3.connect(root / 'tasks.sqlite') as db:
        db.execute('CREATE TABLE tasks(id INTEGER PRIMARY KEY,stage INTEGER,state TEXT,due INTEGER,age INTEGER)')
        db.execute('CREATE INDEX oldest ON tasks(stage,state,age,id)')
        for size in (7000, 70000):
            db.execute('DELETE FROM tasks')
            db.executemany('INSERT INTO tasks VALUES (?,?,?,?,?)',
                ((i, i % 7, 'ready', 0 if i % 3 else 9999999999, i) for i in range(size)))
            db.commit()
            started = time.monotonic()
            for stage in range(7):
                rows = db.execute("SELECT id FROM tasks WHERE stage=? AND state='ready' AND due<=1 "
                                  'ORDER BY age,id LIMIT 256', (stage,)).fetchall()
                assert len(rows) == 256
            scans.append({'rows': size, 'seven_selections_seconds': time.monotonic() - started})
    # Retain the generated bytes. A short fsync measurement is a local lower
    # bound input, not a sustained shared-disk throughput guarantee.
    block = bytes(range(256)) * 4096
    started = time.monotonic()
    path = root / 'io.bin'
    with path.open('wb') as handle:
        for _ in range(64):
            handle.write(block)
        handle.flush()
        import os
        os.fsync(handle.fileno())
    write_seconds = time.monotonic() - started
    started = time.monotonic()
    with path.open('rb') as handle:
        digest = hashlib.file_digest(handle, 'sha256').hexdigest()
    read_seconds = time.monotonic() - started
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss * 1024
    report = {'evidence': str(root), 'source_bytes': len(raw), 'source_parse_seconds': parse_seconds,
        'larger_bytes': len(larger), 'larger_parse_seconds': larger_seconds, 'sqlite_scans': scans,
        'peak_rss_bytes': peak,
        'io_bytes': path.stat().st_size, 'fsync_write_seconds': write_seconds,
        'cached_hash_seconds': read_seconds, 'io_sha256': digest,
        'limits': ['One read-only source snapshot, not live business progress.',
                   'Synthetic larger journal and indexed tasks; not entity conflict acceptance.',
                   'Short local I/O, cached read; 16MiB/s design floor must be monitored, not promised.']}
    assert max(parse_seconds, larger_seconds) < 30
    assert peak < 512 * 1024 * 1024
    assert max(item['seven_selections_seconds'] for item in scans) < .5
    (root / 'report.json').write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
